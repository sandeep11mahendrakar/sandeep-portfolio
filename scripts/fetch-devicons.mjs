import fs from "node:fs";
import path from "node:path";

const REPO = "https://cdn.jsdelivr.net/gh/devicons/devicon@master";
const OUT_DIR = process.argv[2];
const MANIFEST_OUT = process.argv[3];

const VARIANT_PRIORITY = [
  "original",
  "plain",
  "line",
  "original-wordmark",
  "plain-wordmark",
  "line-wordmark",
];

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  return res.json();
}

async function downloadFile(url, dest) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(String(res.status));
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length === 0) throw new Error("empty");
      fs.writeFileSync(dest, buf);
      return true;
    } catch (err) {
      if (attempt === 2) {
        console.warn(`FAILED ${url}: ${err.message}`);
        return false;
      }
      await new Promise((r) => setTimeout(r, 500 * (attempt + 1)));
    }
  }
  return false;
}

function pickVariant(icon) {
  const versions = new Set(icon.versions?.svg ?? []);
  for (const v of VARIANT_PRIORITY) {
    if (versions.has(v)) return v;
  }
  for (const v of versions) {
    if (!v.includes("wordmark")) return v;
  }
  return [...versions][0];
}

async function main() {
  const meta = await fetchJson(`${REPO}/devicon.json`);
  console.log(`devicon index: ${meta.length} icons`);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const jobs = [];
  const chosen = [];
  for (const icon of meta) {
    const variant = pickVariant(icon);
    if (!variant) continue;
    const filename = `${icon.name}-${variant}.svg`;
    chosen.push(filename);
    jobs.push({ url: `${REPO}/icons/${icon.name}/${filename}`, filename });
  }

  let ok = 0;
  const failed = [];
  const BATCH = 12;
  for (let i = 0; i < jobs.length; i += BATCH) {
    const batch = jobs.slice(i, i + BATCH);
    const results = await Promise.all(
      batch.map(async (j) => ({
        j,
        success: await downloadFile(j.url, path.join(OUT_DIR, j.filename)),
      }))
    );
    for (const r of results) {
      if (r.success) ok++;
      else failed.push(r.j.filename);
    }
    if ((i / BATCH) % 5 === 0) console.log(`progress: ${ok}/${jobs.length}`);
  }

  const files = fs
    .readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort();

  const manifest = `// AUTO-GENERATED by scripts/fetch-devicons.mjs — do not edit by hand.\n// Lists Devicon SVG files present in public/icons/tech/.\nexport const TECH_ICON_FILES = [\n${files
    .map((f) => `  "${f}",`)
    .join("\n")}\n] as const;\n\nexport type TechIconFile = (typeof TECH_ICON_FILES)[number];\n`;

  fs.writeFileSync(MANIFEST_OUT, manifest);

  console.log(`downloaded: ${ok}, failed: ${failed.length}, manifest entries: ${files.length}`);
  if (failed.length > 0) console.log("failed files:", JSON.stringify(failed));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
